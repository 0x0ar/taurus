#!/usr/bin/env bash
# Paints the focused-window border of the running compositor with the current
# Taurus palette (Matugen or preset). Called after every color change.
#   niri   : writes config/focus-colors.kdl (live-reloaded) and adds its include
#   mango  : writes config/focus-colors.conf and reloads the config
#   sway, hyprland : applied at runtime (reset by a compositor reload, redone on
#                    the next color change)
#   umbriel: runtime override via `umbriel config set` (reset when the
#            compositor restarts, redone on the next color change)
# Does nothing when the compositor is not recognized.

command -v jq >/dev/null 2>&1 || exit 0
STATE_DIR="${QS_STATE_DIR:-${XDG_STATE_HOME:-$HOME/.local/state}/taurus}"
CFG="${XDG_CONFIG_HOME:-$HOME/.config}"
SRC="$STATE_DIR/qs_colors.json"
[ -f "$SRC" ] || exit 0

active=$(jq -r '.mauve // empty' "$SRC" 2>/dev/null)
inactive=$(jq -r '.surface2 // empty' "$SRC" 2>/dev/null)
hex='^#[0-9a-fA-F]{6}$'
[[ $active =~ $hex && $inactive =~ $hex ]] || exit 0
a=${active#\#}; i=${inactive#\#}

# write_if_changed <path> : reads stdin, replaces <path> only when different
write_if_changed() {
    local out=$1 tmp
    tmp=$(mktemp "$(dirname "$out")/.focus-colors.XXXXXX") || return 1
    cat > "$tmp"
    if cmp -s "$tmp" "$out"; then rm -f "$tmp"; else mv -f "$tmp" "$out"; fi
}

# ensure_include <config> <after-regex> <line> <validate-cmd...>
ensure_include() {
    local conf=$1 after=$2 line=$3; shift 3
    grep -qsF "$line" "$conf" && return 0
    [ ! -L "$conf" ] && [ -w "$conf" ] || return 0
    local tmp="$conf.taurus-focus"
    if sed "s|^\\($after\\)\$|\\1\\n$line|" "$conf" > "$tmp" && grep -qF "$line" "$tmp" \
        && { [ $# -eq 0 ] || "$@" "$tmp" >/dev/null 2>&1; }; then
        mv -f "$tmp" "$conf"
    else
        rm -f "$tmp"
    fi
}

if [ -n "${NIRI_SOCKET:-}" ] || { [ -z "${SWAYSOCK:-}${HYPRLAND_INSTANCE_SIGNATURE:-}${MANGO_INSTANCE_SIGNATURE:-}${UMBRIEL_SOCKET:-}" ] && [ -f "$CFG/niri/config.kdl" ]; }; then
    dir="$CFG/niri"
    [ -f "$dir/config.kdl" ] && [ -d "$dir/config" ] || exit 0
    write_if_changed "$dir/config/focus-colors.kdl" <<KDL
// Generated by Taurus from the current theme. Do not edit.
layout {
    focus-ring {
        active-color "$active"
        inactive-color "$inactive"
    }
}
KDL
    ensure_include "$dir/config.kdl" 'include "config\/layout.kdl"' 'include "config/focus-colors.kdl"' niri validate -c
elif [ -n "${SWAYSOCK:-}" ]; then
    swaymsg "client.focused #$a #$a #ffffff #$a #$a; client.unfocused #$i #$i #ffffff #$i #$i" >/dev/null 2>&1
elif [ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]; then
    hyprctl keyword general:col.active_border "rgba(${a}ff)" >/dev/null 2>&1 \
        || hyprctl eval "hl.config({ general = { [\"col.active_border\"] = \"rgba(${a}ff)\" } })" >/dev/null 2>&1
    hyprctl keyword general:col.inactive_border "rgba(${i}ff)" >/dev/null 2>&1 \
        || hyprctl eval "hl.config({ general = { [\"col.inactive_border\"] = \"rgba(${i}ff)\" } })" >/dev/null 2>&1
elif [ -n "${MANGO_INSTANCE_SIGNATURE:-}" ]; then
    dir="$CFG/mango"
    [ -f "$dir/config.conf" ] && [ -d "$dir/config" ] || exit 0
    write_if_changed "$dir/config/focus-colors.conf" <<CONF
# Generated by Taurus from the current theme. Do not edit.
focuscolor=0x${a}ff
bordercolor=0x${i}ff
CONF
    ensure_include "$dir/config.conf" 'source=\.\/config\/layout\.conf' 'source=./config/focus-colors.conf'
    mmsg dispatch reload_config >/dev/null 2>&1
elif [ -n "${UMBRIEL_SOCKET:-}" ] && command -v umbriel >/dev/null 2>&1; then
    umbriel config set colors.border.focused "\"#${a}ff\"" >/dev/null 2>&1
    umbriel config set colors.border.unfocused "\"#${i}ff\"" >/dev/null 2>&1
    # Persist across compositor restarts by rewriting the two values in place.
    conf="$CFG/umbriel/config.toml"
    if [ -f "$conf" ] && [ ! -L "$conf" ] && [ -w "$conf" ] && grep -q '^\[colors\.border\]' "$conf"; then
        tmp=$(mktemp "$conf.XXXXXX") && sed \
            -e "/^\[colors\.border\]/,/^\[/{s|^focused *=.*|focused = \"#${a}ff\"|;s|^unfocused *=.*|unfocused = \"#${i}ff\"|}" \
            "$conf" > "$tmp" && { cmp -s "$tmp" "$conf" && rm -f "$tmp" || mv -f "$tmp" "$conf"; } || rm -f "$tmp"
    fi
fi
exit 0
